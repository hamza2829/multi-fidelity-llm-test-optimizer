"""Markdown report (docs/results.md)."""

from collections import Counter

from .intents import CATEGORIES, ERROR_TYPES


def pct(x):
    return f"{100 * x:.1f}%"


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def level_table(report):
    rows = []
    for lv in report["levels"]:
        s = report["summaries"][lv]
        rows.append([lv, pct(s["exact_match"]), pct(s["intent_accuracy"]), f"{s['slot_f1']:.3f}",
                     s["failures"], len(s["failure_categories"]),
                     f"{report['total_cost'][lv]:.1f}"])
    return table(["Level", "Exact match", "Intent accuracy", "Slot F1", "Failed tests",
                  "Failure categories", "Cost for 150 tests (s)"], rows)


def category_view(report, tests, results):
    """Confusion-style view: failures per category and level."""
    levels = report["levels"]
    n_by_cat = Counter(t["tags"]["category"] for t in tests)
    rows = []
    for cat in CATEGORIES:
        row = [cat, n_by_cat[cat]]
        for lv in levels:
            fails = [results[lv][t["id"]] for t in tests
                     if t["tags"]["category"] == cat and not results[lv][t["id"]]["passed"]]
            types = Counter(r["error_type"] for r in fails)
            detail = ", ".join(f"{k} {v}" for k, v in types.most_common())
            row.append(f"{len(fails)}" + (f" ({detail})" if detail else ""))
        rows.append(row)
    return table(["Category", "Tests"] + [f"{lv} failures" for lv in levels], rows)


def error_type_view(report):
    levels = report["levels"]
    rows = [[e] + [report["summaries"][lv]["error_types"].get(e, 0) for lv in levels]
            for e in ERROR_TYPES]
    return table(["Error type"] + levels, rows)


def tag_view(report):
    levels = report["levels"]
    rows = []
    for tag in ("difficulty", "language", "noise"):
        for value, info in report["summaries"][levels[0]]["by_tag"][tag].items():
            rows.append([f"{tag}={value}", info["n"]]
                        + [pct(report["summaries"][lv]["by_tag"][tag][value]["accuracy"])
                           for lv in levels])
    return table(["Slice", "Tests"] + [f"{lv} exact match" for lv in levels], rows)


def agreement_view(report):
    rows = []
    for pair, a in report["agreements"].items():
        rows.append([pair.replace("_vs_", " vs "), pct(a["pass_fail_agreement"]), f"{a['kappa']:.2f}",
                     pct(a["same_output"]), a["both_pass"], a["cheap_pass_expensive_fail"],
                     a["cheap_fail_expensive_pass"], a["both_fail"]])
    return table(["Pair (cheap vs expensive)", "Pass/fail agreement", "Cohen kappa",
                  "Identical output", "Both pass", "Cheap pass, expensive fail",
                  "Cheap fail, expensive pass", "Both fail"], rows)


def selection_view(report):
    has_fresh = any("coverage_fresh" in s["method"] for s in report["selection"].values())
    header = ["Method", "Tests", "Cost saved", "Coverage (calibration run)"]
    if has_fresh:
        header += ["Coverage (fresh runs, mean)"]
    header += ["Accuracy estimate error (pp)"]
    rows = []
    for name, sel in report["selection"].items():
        m, r = sel["method"], sel["random_same_size"]
        name = f"{name} ({len(sel['coverage_ids'])} coverage + {len(sel['sample_ids'])} sample)"
        err_key = "estimation_error_fresh" if has_fresh else "estimation_error_calibration"
        sp = sel["method_spread"]
        row = [name, round(m["size"]), f"{pct(m['cost_saved'])} +- {pct(sp['cost_saved']['std'])}",
               f"{pct(m['coverage_calibration'])} +- {pct(sp['coverage_calibration']['std'])}"]
        if has_fresh:
            row.append(f"{pct(m['coverage_fresh'])} +- {pct(sp['coverage_fresh']['std'])}")
        row.append(f"{100 * m[err_key]:.1f} +- {100 * sp[err_key]['std']:.1f}")
        rows.append(row)
        rrow = ["random, same size", round(m["size"]),
                f"{pct(r['cost_saved']['mean'])} +- {pct(r['cost_saved']['std'])}",
                f"{pct(r['coverage_calibration']['mean'])} +- {pct(r['coverage_calibration']['std'])}"]
        if has_fresh:
            rrow.append(f"{pct(r['coverage_fresh']['mean'])} +- {pct(r['coverage_fresh']['std'])}")
        rrow.append(f"{100 * r[err_key]['mean']:.1f} +- {100 * r[err_key]['std']:.1f}")
        rows.append(rrow)
    return table(header, rows)


def write_markdown(report, tests, results, path):
    cfg = report["config"]
    cheap, exp = cfg["cheap_level"], cfg["expensive_level"]
    agree = report["agreements"][f"{cheap}_vs_{exp}"]
    lines = [
        "# Results",
        "",
        "Generated by `python -m mfopt.run`. All numbers come from the synthetic test set "
        f"in `data/testset.json` ({cfg['n_tests']} tests) and the simulated assistant in this repo.",
        "",
    ]
    for note in report["notes"]:
        lines += [f"Note: {note}", ""]
    lines += [
        "## Accuracy by fidelity level", "", level_table(report), "",
        f"Cost is simulated seconds from the test set (`cost` field). High level would use "
        f"about {report['total_high_tokens']} tokens for all tests.", "",
        "## Failures by category and level (confusion-style view)", "",
        category_view(report, tests, results), "",
        "## Failures by error type", "", error_type_view(report), "",
        "## Accuracy by slice", "", tag_view(report), "",
        "## Agreement between levels", "", agreement_view(report), "",
        f"Failure categories (tag=value/error type) found at `{exp}` but not at `{cheap}`: "
        + (", ".join(agree["failure_categories_only_at_expensive"]) or "none") + ".", "",
        f"Failure categories found at `{cheap}` but not at `{exp}`: "
        + (", ".join(agree["failure_categories_only_at_cheap"]) or "none") + ".", "",
        f"## Where the cheap level misses failures ({len(report['cheap_misses'])} tests pass at "
        f"`{cheap}` but fail at `{exp}`)", "",
    ]
    rows = [[m["id"], m["utterance"], m["tags"]["category"], m["expensive_error"],
             f"`{m['expensive_output']}`"] for m in report["cheap_misses"]]
    lines += [table(["Test", "Utterance", "Category", f"{exp} error", f"{exp} output"], rows), ""]
    lines += [
        "## Test selection", "",
        f"Cheap level: `{cheap}` (runs on all tests). Expensive level: `{exp}` (runs on the subset). "
        f"Cost is `{cfg['cost_unit']}`. Each subset = the coverage tests chosen by the method plus "
        f"a random sample of up to {cfg['per_stratum']} cheap-pass and {cfg['per_stratum']} cheap-fail "
        "tests, used to predict the expensive result of the tests that are not run. All rows show "
        f"mean +- std over {cfg['random_seeds']} seeds (the seed changes the prediction sample of a "
        "method, and the whole subset of a random baseline). Random baselines use the same subset "
        "size as the method above them.", "",
        f"Calibration run: {report['calibration_failure_categories']} failure categories. "
        + (f"Fresh runs (seeds {cfg['seed'] + 1} to {cfg['seed'] + cfg['eval_seeds']}): "
           f"{report['fresh_runs_failure_categories']} failure categories."
           if report["fresh_runs_failure_categories"] else ""), "",
        selection_view(report), "",
        "Coverage = share of failure categories (tag=value/error type) of a run that the "
        "subset also detects. Accuracy estimate error = absolute difference between the "
        "estimated and the true expensive-level exact match on all tests, in percentage points, "
        "where the estimate uses cheap results on all tests and expensive results on the subset. "
        f"For comparison, taking the cheap accuracy as the estimate would be off by "
        f"{100 * report['cheap_only_estimate_error']:.1f} pp on the calibration run.",
        "",
        "## Charts", "",
        "![Accuracy by fidelity level](accuracy_by_fidelity.png)", "",
        "![Failures by category](failure_heatmap.png)", "",
        "![Cost vs coverage](cost_vs_coverage.png)", "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
